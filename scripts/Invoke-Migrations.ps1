<#
.SYNOPSIS
    Applies the numbered SQL files in migrations/ to the Postgres database of one environment.

.DESCRIPTION
    Talks to the Postgres container (default sksvc-db) with "docker exec ... psql".
    Steps:
      1. Creates the database (svc_dev or svc_prod) if it does not exist.
      2. Creates the table schema_migrations(filename, applied_at) if it does not exist.
      3. Applies every NNN_name.sql file that is not yet recorded, in numeric order.
    Each file runs in one transaction together with the INSERT that records it,
    so a failing file leaves no partial changes and no record.
    Running the script twice applies nothing the second time.
    Exits 0 on success and 1 on any failure.

.PARAMETER Environment
    dev or prod. Selects the database: dev -> svc_dev, prod -> svc_prod.

.PARAMETER MigrationsPath
    Folder with the .sql files. Default: migrations/ at the repo root.

.PARAMETER ContainerName
    The Postgres container. Default: sksvc-db (the Compose "db" service).

.PARAMETER SecretFile
    File holding the postgres password. Default: .secrets/db_password at the repo root
    (git-ignored, generated by the bring-up script).

.EXAMPLE
    pwsh ./scripts/Invoke-Migrations.ps1 -Environment dev
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [ValidateSet('dev', 'prod')] [string] $Environment,
    [string] $MigrationsPath = (Join-Path -Path $PSScriptRoot -ChildPath '..' -AdditionalChildPath 'migrations'),
    [string] $ContainerName = 'sksvc-db',
    [string] $SecretFile = (Join-Path -Path $PSScriptRoot -ChildPath '..' -AdditionalChildPath '.secrets', 'db_password')
)

Set-StrictMode -Version Latest

# The one place that runs docker. Tests mock this function, so they never need Docker.
# Returns stdout lines; throws with the stderr text if docker exits non-zero.
function Invoke-DockerCommand {
    [CmdletBinding()]
    [OutputType([object[]])]
    param(
        [Parameter(Mandatory)] [string[]] $Arguments,
        [string] $InputText
    )
    # 2>&1 merges stderr into the output as ErrorRecord objects, so we can split them below.
    if ($InputText) {
        $output = $InputText | & docker @Arguments 2>&1
    } else {
        $output = & docker @Arguments 2>&1
    }
    $stdout = @($output | Where-Object { $_ -isnot [System.Management.Automation.ErrorRecord] })
    $stderr = @($output | Where-Object { $_ -is [System.Management.Automation.ErrorRecord] })
    if ($LASTEXITCODE -ne 0) {
        throw "docker $($Arguments[0]) failed (exit $LASTEXITCODE): $($stderr -join ' ')"
    }
    return $stdout
}

# Runs SQL with psql inside the container. Either -Sql (a single command) or
# -InputText (a whole script sent on stdin, run in one transaction).
function Invoke-Psql {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)] [string] $ContainerName,
        [Parameter(Mandatory)] [string] $Database,
        [string] $Sql,
        [string] $InputText
    )
    # -e PGPASSWORD (name only) copies the value from our own environment,
    # so the password never appears on the docker command line.
    # -h 127.0.0.1 connects over TCP. The password is only checked there if the container
    # was initialised with POSTGRES_INITDB_ARGS=--auth-host=scram-sha-256 (otherwise the
    # official image trusts loopback connections).
    # ON_ERROR_STOP=1 makes psql stop and exit non-zero on the first SQL error.
    # -X ignores any .psqlrc; -q -t -A give plain output we can parse.
    $psqlArgs = @('psql', '-h', '127.0.0.1', '-U', 'postgres', '-d', $Database,
        '-v', 'ON_ERROR_STOP=1', '-X', '-q', '-t', '-A')
    if ($InputText) {
        # -i keeps stdin open; --single-transaction wraps the whole script in BEGIN/COMMIT
        # (rolled back on error); -f - reads the script from stdin.
        $fromStdin = @('--single-transaction', '-f', '-')
        $dockerArgs = @('exec', '-i', '-e', 'PGPASSWORD', $ContainerName) + $psqlArgs + $fromStdin
        return Invoke-DockerCommand -Arguments $dockerArgs -InputText $InputText
    }
    $dockerArgs = @('exec', '-e', 'PGPASSWORD', $ContainerName) + $psqlArgs + @('-c', $Sql)
    return Invoke-DockerCommand -Arguments $dockerArgs
}

# Maps the environment to its database name.
function Get-DatabaseName {
    [CmdletBinding()]
    [OutputType([string])]
    param([Parameter(Mandatory)] [ValidateSet('dev', 'prod')] [string] $Environment)
    return "svc_$Environment"
}

# Returns the migration files sorted by their number (001, 002, ... 010 sorts after 009).
# Throws on a .sql file that does not look like NNN_name.sql, so a typo is not silently skipped.
function Get-MigrationFile {
    [CmdletBinding()]
    param([Parameter(Mandatory)] [string] $Path)
    if (-not (Test-Path -Path $Path -PathType Container)) {
        throw "Migrations folder not found: $Path"
    }
    $files = @(Get-ChildItem -Path $Path -Filter '*.sql' -File)
    foreach ($file in $files) {
        # Only digits, lowercase letters and _ : the name is also used inside SQL, so this keeps it safe.
        if ($file.Name -cnotmatch '^\d+_[a-z0-9_]+\.sql$') {
            throw "Bad migration file name '$($file.Name)'. Use NNN_lowercase_name.sql."
        }
    }
    # Sort by the number before the first "_" as an integer, not as text.
    return $files | Sort-Object -Property { [int] ($_.Name -split '_')[0] }
}

# Creates the database and the schema_migrations table if they are missing.
function Initialize-MigrationDatabase {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)] [string] $ContainerName,
        [Parameter(Mandatory)] [string] $Database
    )
    # Connect to the built-in "postgres" database to check whether ours exists.
    $exists = Invoke-Psql -ContainerName $ContainerName -Database 'postgres' `
        -Sql "SELECT 1 FROM pg_database WHERE datname = '$Database'"
    if (-not ($exists -contains '1')) {
        # CREATE DATABASE cannot run inside a transaction, so it is its own command.
        Write-Verbose "Creating database $Database"
        Invoke-Psql -ContainerName $ContainerName -Database 'postgres' -Sql "CREATE DATABASE $Database" | Out-Null
    }
    # filename is the primary key, so the same file can never be recorded twice.
    $createTable = @'
CREATE TABLE IF NOT EXISTS schema_migrations (
    filename   text        PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
)
'@
    Invoke-Psql -ContainerName $ContainerName -Database $Database -Sql $createTable | Out-Null
}

# Returns the file names already recorded in schema_migrations.
function Get-AppliedMigration {
    [CmdletBinding()]
    [OutputType([object[]])]
    param(
        [Parameter(Mandatory)] [string] $ContainerName,
        [Parameter(Mandatory)] [string] $Database
    )
    $rows = Invoke-Psql -ContainerName $ContainerName -Database $Database `
        -Sql 'SELECT filename FROM schema_migrations ORDER BY filename'
    # Drop empty lines; psql prints nothing at all when the table is empty.
    return @($rows | Where-Object { "$_".Trim() -ne '' } | ForEach-Object { "$_".Trim() })
}

# Main logic. Returns the names of the files applied in this run.
function Invoke-Migration {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory)] [ValidateSet('dev', 'prod')] [string] $Environment,
        [Parameter(Mandatory)] [string] $MigrationsPath,
        [Parameter(Mandatory)] [string] $ContainerName,
        [Parameter(Mandatory)] [string] $SecretFile
    )
    if (-not (Test-Path -Path $SecretFile -PathType Leaf)) {
        throw "Password file not found: $SecretFile (run the bring-up script first)."
    }
    $database = Get-DatabaseName -Environment $Environment
    $files = Get-MigrationFile -Path $MigrationsPath

    # psql reads PGPASSWORD from the environment that docker exec passes in.
    # Remember the old value and restore it afterwards, so the secret does not linger.
    $previousPassword = $env:PGPASSWORD
    $env:PGPASSWORD = (Get-Content -Path $SecretFile -Raw).Trim()
    try {
        Initialize-MigrationDatabase -ContainerName $ContainerName -Database $database
        $applied = Get-AppliedMigration -ContainerName $ContainerName -Database $database

        $newlyApplied = @()
        foreach ($file in $files) {
            if ($applied -contains $file.Name) {
                Write-Verbose "Skipping $($file.Name) (already applied)"
                continue
            }
            # The file and the INSERT that records it go in one transaction:
            # either both happen or neither does.
            $fileSql = Get-Content -Path $file.FullName -Raw
            $recordSql = "INSERT INTO schema_migrations (filename) VALUES ('$($file.Name)');"
            $sql = "$fileSql`n$recordSql`n"
            Write-Verbose "Applying $($file.Name)"
            try {
                Invoke-Psql -ContainerName $ContainerName -Database $database -InputText $sql | Out-Null
            } catch {
                throw "Migration $($file.Name) failed and was rolled back: $($_.Exception.Message)"
            }
            $newlyApplied += $file.Name
        }
        return $newlyApplied
    } finally {
        $env:PGPASSWORD = $previousPassword
    }
}

# Main: only runs when the script is executed, not when tests dot-source it.
if ($MyInvocation.InvocationName -ne '.') {
    try {
        $done = @(Invoke-Migration -Environment $Environment -MigrationsPath $MigrationsPath `
                -ContainerName $ContainerName -SecretFile $SecretFile)
        if ($done.Count -eq 0) {
            Write-Output "Migrations ($Environment): nothing to apply, database is up to date."
        } else {
            Write-Output "Migrations ($Environment): applied $($done.Count) file(s): $($done -join ', ')"
        }
        exit 0
    } catch {
        Write-Error "Migrations ($Environment) failed: $($_.Exception.Message)" -ErrorAction Continue
        exit 1
    }
}
